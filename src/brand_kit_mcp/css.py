"""Export brand tokens as CSS custom properties on ``:root``.

The CSS is generated from the same conversion as the DTCG export, so both always agree on which
tokens exist. Values are rebuilt from validated data (never copied verbatim), which keeps the
output free of injected CSS.
"""

from __future__ import annotations

import re

from . import __version__
from .catalog import Brand
from .dtcg import FONT_WEIGHT_KEYWORDS, DtcgToken, convert_tokens

PREFIX_RE = re.compile(r"^[a-z][a-z0-9-]{0,31}$")
GENERIC_FAMILIES = frozenset(
    {
        "serif",
        "sans-serif",
        "monospace",
        "cursive",
        "fantasy",
        "system-ui",
        "ui-serif",
        "ui-sans-serif",
        "ui-monospace",
        "ui-rounded",
        "emoji",
        "math",
        "fangsong",
    }
)


def css_variable(path: tuple[str, ...], prefix: str = "") -> str:
    parts = [p for p in path if p != "$root"]
    name = "-".join(re.sub(r"[^A-Za-z0-9-]", "-", p) for p in parts).lower()
    return f"--{prefix}-{name}" if prefix else f"--{name}"


def css_value(token: DtcgToken) -> str:
    value = token.value
    if token.type == "color":
        alpha = value.get("alpha")
        if alpha is None:
            return value["hex"]
        return value["hex"] + f"{round(alpha * 255):02X}"
    if token.type == "fontFamily":
        names = value if isinstance(value, list) else [value]
        return ", ".join(n if n.lower() in GENERIC_FAMILIES else f'"{n}"' for n in names)
    if token.type == "fontWeight":
        return str(FONT_WEIGHT_KEYWORDS.get(value, value))
    if token.type == "dimension":
        return f"{value['value']}{value['unit']}"
    return str(value)


def export_css(brand: Brand, prefix: str = "") -> str:
    """Render ``:root { --color-primary: ...; }`` for a brand."""
    prefix = (prefix or "").strip()
    if prefix and not PREFIX_RE.match(prefix):
        raise ValueError("prefix must be 1-32 lowercase letters, digits or '-', starting with a letter")
    _, exported, omitted = convert_tokens(brand.tokens)
    lines = [
        f"/* {brand.name} ({brand.slug}) design tokens. Generated by brand-kit-mcp {__version__}; do not edit. */",
        ":root {",
    ]
    seen: dict[str, str] = {}
    skipped: list[str] = []
    for token in exported:
        variable = css_variable(token.path, prefix)
        if variable in seen:
            skipped.append(f"{token.name} (same variable as {seen[variable]})")
            continue
        seen[variable] = token.name
        lines.append(f"  {variable}: {css_value(token)};")
    lines.append("}")
    notes = [f"{o['name']} ({o['reason']})" for o in omitted] + skipped
    if notes:
        lines.append("/* Not exported: " + ", ".join(notes).replace("*/", "") + " */")
    return "\n".join(lines) + "\n"
